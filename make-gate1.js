/* ════════════════════════════════════════════════════════════════════
   make-gate1.js — builds gate_1.html (GATE-1, Unit-1 / Store 1) from gate_2.html
   ────────────────────────────────────────────────────────────────────
   gate_1.html is a full COPY of gate_2.html (chosen on purpose), so every
   change to the Gate-2 page must reach Gate-1 too. Make the change in
   gate_2.html, then run:   node make-gate1.js
   (from this folder). It rewrites gate_1.html from scratch with exactly these
   differences, and refuses to run when one of them is not found (so a renamed
   line in gate_2.html can never silently produce a wrong Gate-1):
     GATE_ID 'G1'                      -> its own register rows, G1- numbers, Store 1 lists,
                                          "the other gate" = Gate-2 (gate-link.js reads these)
     app key HOME_GATE1                -> its own launcher tile / rights (sso-gate.js)
     phone storage keys gate1_* / g1iosGate*  -> both gates can be used on ONE phone
     the visible names GATE-1 / Gate-1
   The shared between-gates code lives in gate-link.js (loaded by both), so it
   is not copied. Not used by any page at run time.
   ════════════════════════════════════════════════════════════════════ */
'use strict';
const fs = require('fs'), path = require('path');
const dir = __dirname;
let s = fs.readFileSync(path.join(dir, 'gate_2.html'), 'utf8');

function once(a, b) { const n = s.split(a).length - 1; if (n !== 1) throw new Error('expected 1 x "' + a + '", found ' + n); s = s.replace(a, b); }
function all(a, b, min) { const n = s.split(a).length - 1; if (n < (min || 1)) throw new Error('expected "' + a + '" at least ' + (min || 1) + ' time(s), found ' + n); s = s.split(a).join(b); return n; }

once("const GATE_ID = 'G2';", "const GATE_ID = 'G1';");
once("const GATE_APP = 'HOME_GATE2';", "const GATE_APP = 'HOME_GATE1';");
const keys = all("'gate2_", "'gate1_", 7) + all("'iosGate", "'g1iosGate", 4);
once('<title>SARV INDIA GATE-2</title>', '<title>SARV INDIA GATE-1</title>');
once('SARV INDIA <span class="text-blue-600">GATE-2</span>', 'SARV INDIA <span class="text-blue-600">GATE-1</span>');
once('<h2 class="text-lg font-extrabold tracking-tight text-gray-900">SARV INDIA GATE-2</h2>', '<h2 class="text-lg font-extrabold tracking-tight text-gray-900">SARV INDIA GATE-1</h2>');
once("software: 'SARV INDIA GATE-2',", "software: 'SARV INDIA GATE-1',");
once("'This module is scheduled for the next SARV INDIA GATE-2 update.'", "'This module is scheduled for the next SARV INDIA GATE-1 update.'");
once("label: 'Gate-2' });", "label: 'Gate-1' });");
once('• Exited Gate-2`;', '• Exited Gate-1`;');
once("console.warn('[Gate-2] could not read '", "console.warn('[Gate-1] could not read '");
once("console.error('Gate-2 start failed'", "console.error('Gate-1 start failed'");
once("console.error('[Gate-2] sync failed'", "console.error('[Gate-1] sync failed'");

s = s.replace('<head>', '<head>\n<!-- GENERATED by make-gate1.js from gate_2.html: do not edit here. Change gate_2.html, then run: node make-gate1.js -->');
fs.writeFileSync(path.join(dir, 'gate_1.html'), s);
console.log('gate_1.html written (' + Math.round(s.length / 1024) + ' KB, ' + keys + ' storage keys renamed)');
